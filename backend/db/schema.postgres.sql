    observaciones TEXT COLLATE "C",
    fecha_registro TEXT COLLATE "C" NOT NULL DEFAULT fecha_actual_utc(),
    FOREIGN KEY (id_usuario) REFERENCES usuarios(id_usuario) ON UPDATE CASCADE ON DELETE CASCADE
);

