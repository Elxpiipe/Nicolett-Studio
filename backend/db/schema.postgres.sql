    fecha_creacion TEXT COLLATE "C" NOT NULL DEFAULT fecha_actual_utc(),
    CHECK (fecha_hora_inicio < fecha_hora_fin),
    FOREIGN KEY (id_profesional) REFERENCES profesionales(id_profesional) ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS citas (
    id_cita INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_cita TEXT COLLATE "C" NOT NULL UNIQUE,
    id_cliente INTEGER NOT NULL,
    id_profesional INTEGER NOT NULL,
