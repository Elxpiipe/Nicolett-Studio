-- db/schema.postgres.sql
-- Esquema de Nicolett Sync para PostgreSQL. Equivale a schema.sql (SQLite) mas
-- todos los cambios de migrations.sql y migraciones.js, ya incorporados.
-- Se puede ejecutar varias veces: no borra tablas ni datos (IF NOT EXISTS).
-- Uso: npm run db:init
--
-- Notas sobre los tipos (para que todo funcione igual que con SQLite):
--  * Fechas y horas siguen como texto 'AAAA-MM-DD HH:MM' / 'HH:MM', como las
--    escribe y compara el backend (ver src/utils/fechas.js).
--  * COLLATE "C" compara y ordena el texto byte a byte, igual que SQLite.
--  * CITEXT reemplaza a COLLATE NOCASE (correo y codigo de cupon sin
--    distinguir mayusculas).
--  * fecha_actual_utc() reemplaza a CURRENT_TIMESTAMP y devuelve el mismo
--    formato que SQLite: 'AAAA-MM-DD HH:MM:SS' en UTC.

CREATE EXTENSION IF NOT EXISTS citext;

CREATE OR REPLACE FUNCTION fecha_actual_utc() RETURNS text
LANGUAGE sql STABLE
AS $$ SELECT to_char(statement_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS') $$;

