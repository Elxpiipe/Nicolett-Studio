CREATE TABLE IF NOT EXISTS roles (
    id_rol INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT COLLATE "C" NOT NULL UNIQUE,
    descripcion TEXT COLLATE "C",
    activo INTEGER NOT NULL DEFAULT 1 CHECK (activo IN (0,1))
);

CREATE TABLE IF NOT EXISTS usuarios (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rol INTEGER NOT NULL,
    rut TEXT COLLATE "C" UNIQUE,
    nombres TEXT COLLATE "C" NOT NULL,
    apellidos TEXT COLLATE "C" NOT NULL,
    email CITEXT NOT NULL UNIQUE,
    telefono TEXT COLLATE "C",
    password_hash TEXT COLLATE "C" NOT NULL,
    activo INTEGER NOT NULL DEFAULT 1 CHECK (activo IN (0,1)),
    fecha_creacion TEXT COLLATE "C" NOT NULL DEFAULT fecha_actual_utc(),
    fecha_actualizacion TEXT COLLATE "C" NOT NULL DEFAULT fecha_actual_utc(),
    es_invitado INTEGER NOT NULL DEFAULT 0,
    FOREIGN KEY (id_rol) REFERENCES roles(id_rol) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS clientes (
    id_cliente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INTEGER NOT NULL UNIQUE,
