    id_cupon INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo CITEXT NOT NULL UNIQUE,
    nombre TEXT COLLATE "C" NOT NULL,
    descripcion TEXT COLLATE "C",
    tipo_descuento TEXT COLLATE "C" NOT NULL CHECK (tipo_descuento IN ('PORCENTAJE','MONTO')),
    valor_descuento INTEGER NOT NULL CHECK (valor_descuento > 0),
    fecha_inicio TEXT COLLATE "C" NOT NULL,
    fecha_fin TEXT COLLATE "C" NOT NULL,
    max_usos INTEGER CHECK (max_usos IS NULL OR max_usos > 0),
    activo INTEGER NOT NULL DEFAULT 1 CHECK (activo IN (0,1)),
    CHECK (fecha_inicio <= fecha_fin),
    CHECK ((tipo_descuento = 'PORCENTAJE' AND valor_descuento BETWEEN 1 AND 100) OR (tipo_descuento = 'MONTO' AND valor_descuento > 0))
);

