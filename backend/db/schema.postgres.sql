CREATE TABLE IF NOT EXISTS pagos (
    id_pago INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cita INTEGER,
    id_venta INTEGER,
    tipo_pago TEXT COLLATE "C" NOT NULL CHECK (tipo_pago IN ('ABONO_CITA','PAGO_VENTA','DEVOLUCION')),
    monto INTEGER NOT NULL CHECK (monto > 0),
    metodo_pago TEXT COLLATE "C" NOT NULL CHECK (metodo_pago IN ('EFECTIVO','DEBITO','CREDITO','TRANSFERENCIA','PASARELA_WEB')),
    estado TEXT COLLATE "C" NOT NULL DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE','APROBADO','RECHAZADO','ANULADO')),
    id_transaccion_externa TEXT COLLATE "C" UNIQUE,
    fecha_pago TEXT COLLATE "C" NOT NULL DEFAULT fecha_actual_utc(),
    detalle_pasarela TEXT COLLATE "C",
    CHECK ((tipo_pago = 'ABONO_CITA' AND id_cita IS NOT NULL) OR (tipo_pago = 'PAGO_VENTA' AND id_venta IS NOT NULL) OR (tipo_pago = 'DEVOLUCION' AND (id_cita IS NOT NULL OR id_venta IS NOT NULL))),
