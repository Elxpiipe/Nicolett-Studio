    id_detalle INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_venta INTEGER NOT NULL,
    tipo_item TEXT COLLATE "C" NOT NULL CHECK (tipo_item IN ('PRODUCTO','SERVICIO')),
    id_producto INTEGER,
    id_servicio INTEGER,
    descripcion TEXT COLLATE "C" NOT NULL,
    cantidad DOUBLE PRECISION NOT NULL DEFAULT 1 CHECK (cantidad > 0),
    precio_unitario INTEGER NOT NULL CHECK (precio_unitario >= 0),
    descuento INTEGER NOT NULL DEFAULT 0 CHECK (descuento >= 0),
    subtotal INTEGER NOT NULL CHECK (subtotal >= 0),
    CHECK ((tipo_item = 'PRODUCTO' AND id_producto IS NOT NULL AND id_servicio IS NULL) OR (tipo_item = 'SERVICIO' AND id_servicio IS NOT NULL AND id_producto IS NULL)),
    FOREIGN KEY (id_venta) REFERENCES ventas(id_venta) ON UPDATE CASCADE ON DELETE CASCADE,
    FOREIGN KEY (id_producto) REFERENCES productos(id_producto) ON UPDATE CASCADE ON DELETE RESTRICT,
