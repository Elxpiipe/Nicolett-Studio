CREATE TABLE IF NOT EXISTS ventas (
    id_venta INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente INTEGER,
    id_cita INTEGER,
    id_usuario_cajero INTEGER NOT NULL,
    subtotal INTEGER NOT NULL DEFAULT 0 CHECK (subtotal >= 0),
    descuento INTEGER NOT NULL DEFAULT 0 CHECK (descuento >= 0),
    total INTEGER NOT NULL DEFAULT 0 CHECK (total >= 0),
    estado TEXT COLLATE "C" NOT NULL DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE','PAGADA','ANULADA')),
    fecha TEXT COLLATE "C" NOT NULL DEFAULT fecha_actual_utc(),
    codigo_venta TEXT COLLATE "C",
    canal TEXT COLLATE "C" NOT NULL DEFAULT 'LOCAL',
    fecha_expiracion_pago TEXT COLLATE "C",
    stock_reservado INTEGER NOT NULL DEFAULT 0,
    fecha_pago TEXT COLLATE "C",
    fecha_entrega TEXT COLLATE "C",
    notas TEXT COLLATE "C",
    motivo_anulacion TEXT COLLATE "C",
    CHECK (descuento <= subtotal),
    FOREIGN KEY (id_cliente) REFERENCES clientes(id_cliente) ON UPDATE CASCADE ON DELETE SET NULL,
    FOREIGN KEY (id_cita) REFERENCES citas(id_cita) ON UPDATE CASCADE ON DELETE SET NULL,
    FOREIGN KEY (id_usuario_cajero) REFERENCES usuarios(id_usuario) ON UPDATE CASCADE ON DELETE RESTRICT
