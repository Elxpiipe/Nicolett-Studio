    fecha_hora_fin TEXT COLLATE "C" NOT NULL,
    estado TEXT COLLATE "C" NOT NULL DEFAULT 'PENDIENTE_ABONO' CHECK (estado IN ('PENDIENTE_ABONO','CONFIRMADA','ATENDIDA','CANCELADA','NO_ASISTE')),
    notas_cliente TEXT COLLATE "C",
    fecha_creacion TEXT COLLATE "C" NOT NULL DEFAULT fecha_actual_utc(),
    fecha_cancelacion TEXT COLLATE "C",
